//! 콘텐츠 뷰 사건의 **이름과 축** — 내는 쪽과 듣는 쪽이 합의해야 할 것만 산다. 발행 코드는 없다.
//!
//! **왜 코어가 아닌가.** 발행자는 프레임워크이고(`frameworks/*/…/webview*`), 소비자는 앱과
//! 플러그인이다. 코어는 어느 쪽도 아니다 — 콘텐츠 뷰를 여는 명령(`webview_open`·`navigate`)도
//! 코어에 없고 프레임워크가 진다. 소유하지 않는 사실을 코어에 두면 코어가 자기 위층을 알게
//! 된다. 그래서 `spec-*` 형제들과 같은 자리에 산다: 양쪽이 합의할 것의 단일 진실.
//!
//! **왜 이름을 한 자리에 두는가.** 같은 사건을 두 곳이 낸다 — 콘텐츠가 프로세스 밖에 사는
//! 프레임워크는 Rust 가 emit 하고, DOM 안에 사는 프레임워크는 렌더러가 그 자리에서 뿌린다
//! (`src/lib/contentViewEvents.ts`). 구독자는 어디서 왔는지 모른다. 이름이나 필드가 갈리면
//! **한쪽 프레임워크에서만 아무 일도 안 일어난다.**
//!
//! 실측(2026-08-01): Rust 페이로드가 `rename_all = "camelCase"` 라 `canBack`·`canForward` 를
//! 내는데 TS 는 `can_back`·`can_forward` 를 실었다. 소비자는 카멜을 읽으므로 그 프레임워크에서는
//! **뒤로가기 버튼이 항상 비활성**이었다. 오류는 아무 데도 안 났다.
//!
//! **이름에 `browser` 가 없다.** 여기 있는 사실들 — 주소가 바뀌었다·제목이 바뀌었다·적재
//! 중이다 — 은 무엇이 담겼든 콘텐츠 뷰의 사실이지 브라우저의 사실이 아니다. 브라우저는 이
//! 뷰에 사는 플러그인 하나일 뿐이다.

/// 항행 — 주소가 바뀌었다.
pub const NAV: &str = "content-view-navigated";
/// 제목이 바뀌었다.
pub const TITLE: &str = "content-view-title";
/// 적재 시작/끝 — 뒤·앞 가능 여부를 함께 싣는다.
pub const LOADING: &str = "content-view-loading";
/// 마우스가 가리키는 링크 등 상태줄 사실.
pub const STATUS: &str = "content-view-status";
/// 이 뷰가 열 수 없는 주소 — 밖으로 넘긴다.
pub const OPEN_EXTERNAL: &str = "content-view-open-external";

/// `LOADING` 이 싣는 축. **카멜이다** — 소비자가 그렇게 읽는다.
pub const LOADING_FIELDS: &[&str] = &["label", "loading", "canBack", "canForward"];

#[cfg(test)]
mod tests {
    use super::*;

    /// 이름은 접두사를 공유한다 — 구독자가 `content-view-` 로 거른다.
    ///
    /// 접두사에 특정 기능의 낱말을 쓰지 않는다(C1). 옛 판은 `browser-` 였고, 그래서 코어가
    /// 자기 위에 사는 플러그인의 이름을 알고 있었다 — 이 갈래의 사실들은 무엇이 담겼든
    /// 콘텐츠 뷰의 사실이다.
    #[test]
    fn 모든_이름이_같은_갈래에_산다() {
        for n in [NAV, TITLE, LOADING, STATUS, OPEN_EXTERNAL, ACTIVATED] {
            assert!(n.starts_with("content-view-"), "{n}");
            assert!(!n.contains("browser"), "코어가 플러그인의 낱말을 안다: {n}");
        }
    }

    /// 적재 축은 카멜이다. 스네이크로 내면 소비자가 undefined 를 읽고, 그것은 오류가 아니라
    /// **항상 비활성인 버튼**으로 나타난다.
    #[test]
    fn 적재_축은_카멜이다() {
        assert!(LOADING_FIELDS.contains(&"canBack"));
        assert!(LOADING_FIELDS.contains(&"canForward"));
        assert!(!LOADING_FIELDS.iter().any(|f| f.contains('_')));
    }
}

/// 사용자가 이 콘텐츠 뷰를 눌렀다 — **칸 결합이 따라가야 할 유일한 사실.**
///
/// **모든 프레임워크가 내지 않는다. 그 비대칭은 선언이다.**
///
/// 공통 사실은 하나다: 콘텐츠 뷰 위의 클릭을 호스트 문서가 못 본다. 그런데 프레임워크가 아는
/// 것이 다르다.
///
/// - 콘텐츠가 문서 밖 네이티브 자식인 프레임워크는 OS 입력 모니터에서 **좌표**를 안다. 앱이
///   그 점으로 요소를 짚으면(`elementFromPoint`) 칸이 바로 나온다 — 네이티브 자식이 DOM 위에
///   떠 있을 뿐 그 아래에 칸이 그대로 있기 때문이다. 그래서 이 사건이 필요 없다.
/// - 콘텐츠가 문서 안이되 **다른 프로세스**인 프레임워크(`<webview>`)는 좌표를 모른다. 호스트
///   좌표계로 환산할 근거가 없고, 아는 것은 "어느 guest 가 눌렸나"뿐이다. 그래서 이 사건이
///   그 프레임워크의 유일한 통로다.
///
/// 좌표를 아는 쪽에 라벨까지 내게 하지 않는다. 그러면 "이 점에 어느 뷰가 있나"의 답이 Rust 와
/// DOM 두 곳이 되고, 둘이 갈리는 순간은 조용하다. **답은 한 곳에서만 온다.**
///
/// 앱은 어느 길로 들어오든 **같은 함수**로 칸을 짚는다(`bindPaneUnder`). 계약은 그 자리 하나다.
///
/// 이름에 `browser` 가 없다. 코어가 아는 실체는 **콘텐츠 뷰**이고 "브라우저"는 그 위에 사는
/// 플러그인의 낱말이다 — 코어가 그 낱말을 알면 특정 기능을 아는 것이다(C1). 그리고 이 사실은
/// 브라우저의 것도 아니다: 콘텐츠 뷰면 무엇이 담겼든 누르면 결합이 따라가야 한다.
///
/// 콘텐츠는 프로세스가 갈리므로 그 안의 클릭이 호스트 문서에 아무것도 안 남긴다(계측
/// 2026-08-02: 브라우저 안을 눌렀을 때 호스트에 도착한 사건이 0 이었다). 그 사실을 아는 것은
/// 프레임워크뿐이고, 알아내는 방법은 프레임워크마다 다르다 — 네이티브 입력 모니터, guest 의
/// 입력 사건. **방법이 갈려도 이름은 하나다.** 이름이 갈리면 앱이 프레임워크마다 다른 것을
/// 들어야 하고, 세 번째가 오면 세 번째 이름이 생긴다.
///
/// 페이로드는 `{ label }` — 어느 뷰인지가 사실이다. 좌표는 싣지 않는다: 좌표는 알아낸 방법의
/// 흔적이지 사실이 아니고, 그것을 실으면 그 방법이 없는 프레임워크가 못 낸다.
pub const ACTIVATED: &str = "content-view-activated";
