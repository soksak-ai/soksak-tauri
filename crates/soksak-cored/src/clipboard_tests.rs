use super::*;

/// 안 돌고 있으면 "안 돈다"고 답한다 — 물어서 아는 자리가 없으면 두 번 시작하는 길이 생긴다.
#[test]
fn watching_is_false_before_start() {
    watch_stop();
    assert!(!watching());
}

/// 안 도는 것을 멈추는 것은 성공이다(멱등) — 없음을 오류로 만들면 회수 경로가 두 번째에 실패한다.
#[test]
fn stopping_when_idle_is_fine() {
    watch_stop();
    watch_stop();
    assert!(!watching());
}
