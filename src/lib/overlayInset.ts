// 겹침으로 가릴 수 없는 표면 — **상자를 줄인다.**
//
// 콘텐츠 뷰(네이티브 자식·게스트 프레임)는 별도 합성 레이어라 DOM 의 z-index 를 무시하고 위로
// 올라온다. 그래서 오버레이 패널을 그 위에 띄워도 가려지지 않는다(실측 2026-08-02: 우측
// 사이드바를 오버레이로 두니 브라우저가 581px 를 뚫고 그 위에 그려졌다 — 뷰 상자가 x=304
// w=1092 로 사이드바 시작점 815 를 넘고 있었다).
//
// 규칙은 하나다: **오버레이가 차지한 폭만큼 판의 쓸 수 있는 영역이 줄어든다.** 겹침에 기대지
// 않으므로 프레임워크가 무엇이든 같다. 밀기 모드는 이미 흐름에서 자리를 가져가므로 0 이다.
//
// 값이 아니라 이 함수를 쓴다. 두 자리가 각자 계산하면 한쪽만 고쳐지고, 그 어긋남은 "가끔
// 브라우저가 패널 위로 올라온다"로 나타난다.

/** 오른쪽에서 판을 덮은 폭(px). 덮지 않으면 0. */
export function overlayRightInset(input: {
  open: boolean;
  mode: "overlay" | "push";
  width: number;
}): number {
  if (!input.open) return 0;
  // 밀기는 흐름에서 자리를 가져간다 — 판이 이미 그만큼 좁다. 또 빼면 두 번 빼는 것이다.
  if (input.mode === "push") return 0;
  return Math.max(0, input.width);
}
