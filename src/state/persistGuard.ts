// 모르는 것으로 아는 것을 덮지 않는다 — **복원에 실패했으면 저장하지 않는다.**
//
// 빈 상태에는 두 얼굴이 있다: "사용자가 다 닫았다"와 "복원이 실패했다". 앞엣것은 사용자 의도라
// 저장해야 하고, 뒤엣것은 아직 아무것도 모르는 상태라 저장하면 **아는 것을 지운다.**
//
// 실측(2026-08-01, 두 번): 복원이 예외로 죽자 창이 비었고 그 빈 상태가 곧바로 저장되어 스냅샷을
// 덮었다(10KB → 32바이트). 복원 실패는 일시적일 수 있지만 덮어쓰기는 영구다 — 백업 링이 없었다면
// 사용자 워크스페이스 셋이 그대로 사라졌다.

/** 저장 여부를 가르는 사실 — 셋 다 수이고, 판정은 이 값들만 본다. */
export interface PersistFacts {
  /** 복원 시점 스냅샷에 있던 프로젝트 수. 이것이 "우리가 알고 있던 것"이다. */
  snapshotProjects: number;
  /** 복원이 실제로 세운 프로젝트 수(P6 드롭 뒤). */
  restoredProjects: number;
  /** 지금 이 창에 있는 프로젝트 수. */
  liveProjects: number;
}

/**
 * 지금 상태를 저장해도 되는가.
 *
 * 막는 경우는 하나다: **알던 것이 있었는데 하나도 못 살렸고 지금도 비어 있다.** 그때의 빈 상태는
 * 사용자 의도가 아니라 복원 실패의 흔적이고, 그것을 저장하면 알던 것이 사라진다.
 *
 * 일부만 살아난 것은 실패가 아니다 — 다른 창이 점유한 root 를 드롭하는 것은 규칙(P6)이다.
 */
export function mayPersist(f: PersistFacts): boolean {
  if (f.snapshotProjects === 0) return true;
  if (f.restoredProjects > 0 || f.liveProjects > 0) return true;
  return false;
}
