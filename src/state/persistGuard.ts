// 모르는 것으로 아는 것을 덮지 않는다 — **복원에 실패했으면 저장하지 않는다.**
//
// 빈 상태에는 두 얼굴이 있다: "사용자가 다 닫았다"와 "복원이 실패했다". 앞엣것은 사용자 의도라
// 저장해야 하고, 뒤엣것은 아직 아무것도 모르는 상태라 저장하면 **아는 것을 지운다.**
//
// 실측(2026-08-01, 세 번): 복원이 예외로 죽자 창이 비었고 그 빈 상태가 곧바로 저장되어 스냅샷을
// 덮었다(10KB → 32바이트). 복원 실패는 일시적일 수 있지만 덮어쓰기는 영구다 — 백업 링이 없었다면
// 사용자 워크스페이스 셋이 그대로 사라졌다.
//
// [RULE] **못 읽은 것은 비어 있는 것이 아니다.** 저장소 주인은 별도 프로세스(cored)이므로 읽기는
// 실패할 수 있다. 그 실패를 수 0 으로 적으면 "원래 빈 창"과 **같은 값**이 되고, 가드는 그 순간
// 문을 연다 — 3차 소실(13:24 실측)이 정확히 그 길이었다. 그래서 이 파일은 읽기 결과를 수가 아니라
// **읽었는가가 드러나는 값**으로 받는다. 못 읽음은 0 으로 표현될 수 없다.

/** 스냅샷 읽기 결과. 못 읽음이 수(0)로 둔갑하지 못하도록 읽음 여부를 값에 담는다. */
export type SnapshotRead = { read: true; projects: number } | { read: false };

/** 읽었다 — 스냅샷에 프로젝트가 이만큼 있었다(0 이면 정말로 비어 있었다). */
export function snapshotRead(projects: number): SnapshotRead {
  return { read: true, projects };
}

/** 못 읽었다 — 저장소가 답하지 않았다. 무엇이 들어 있는지 모르는 상태다. */
export function snapshotUnread(): SnapshotRead {
  return { read: false };
}

/** 저장 여부를 가르는 사실. 판정은 이 값들만 본다. */
export interface PersistFacts {
  /** 복원 시점 스냅샷을 읽은 결과. 이것이 "우리가 알고 있던 것"이다. */
  snapshot: SnapshotRead;
  /** 복원이 실제로 세운 프로젝트 수(P6 드롭 뒤). */
  restoredProjects: number;
  /** 지금 이 창에 있는 프로젝트 수. */
  liveProjects: number;
}

/**
 * 지금 상태를 저장해도 되는가.
 *
 * 막는 경우는 둘이다.
 *
 *  1. **못 읽었다.** 무엇을 덮는지 모르므로 쓰지 않는다. 지금 창이 차 있어도 마찬가지다 —
 *     "차 있으니 안전하다"는 판정은 아래 있는 것을 알 때만 성립한다. 기본 부트로 세운 하나가
 *     스냅샷의 셋을 덮은 것이 3차 소실이다.
 *  2. **알던 것이 있었는데 하나도 못 살렸고 지금도 비어 있다.** 그때의 빈 상태는 사용자 의도가
 *     아니라 복원 실패의 흔적이고, 그것을 저장하면 알던 것이 사라진다.
 *
 * 일부만 살아난 것은 실패가 아니다 — 다른 창이 점유한 root 를 드롭하는 것은 규칙(P6)이다.
 */
export function mayPersist(f: PersistFacts): boolean {
  if (!f.snapshot.read) return false;
  if (f.snapshot.projects === 0) return true;
  if (f.restoredProjects > 0 || f.liveProjects > 0) return true;
  return false;
}

/**
 * 부트에서 못 읽은 창이 **쓰기 직전에 다시 읽었다.** 그 결과를 부트 사실로 채택해도 되는가.
 *
 * 못 읽었다고 영영 안 쓰면 그것도 손실이다 — 그래서 다시 읽을 길은 있어야 한다. 그런데 늦게
 * 읽어 **내용이 나오면** 이 창은 그것을 복원한 적이 없다. 그 상태로 저장하면 복원한 적 없는
 * 창이 남의 내용을 덮는다 — 막으려던 그 손이다.
 *
 * 그래서 채택은 **비어 있을 때만**이다. 비어 있으면 덮을 것이 없으니 이제 정상으로 쓰면 되고,
 * 차 있으면 쓰지 않는다(그 창의 올바른 회복은 저장이 아니라 다시 복원하는 것이다).
 */
export function mayAdoptLateRead(projects: number): boolean {
  return projects === 0;
}
