// 이 실행물을 끈다 — 끌 수 있는 이름이 있어야 검증할 수 있다.
//
// 하니스가 앱을 끄려고 운영체제를 빌렸다(`osascript ... to quit`). 끌 이름이 없었기 때문이다.
// 부를 수 없는 것은 검증할 수 없고, 없으면 만드는 것까지가 이 자리의 몫이다(A27).
//
// **이 명령은 자기 죽음을 기록하지 못한다.** 종료가 기록보다 먼저 끝난다. 그래서 끄기 전에 그
// 사실을 남기고 끈다 — 원장에 없으면 "끄라는 말을 못 들었다"와 "듣고 죽었다"를 구분할 수 없다.
//
// 답을 먼저 돌려주고 끈다. 종료가 답보다 앞서면 부른 쪽은 소켓이 끊긴 것만 보고, 그것이 성공인지
// 사고인지 알 수 없다.

const { app } = require("electron");

module.exports = {
  app_quit: {
    concept: "이 실행물 종료",
    answer: (ctx) => {
      ctx.note("[electron] app.quit — 명령으로 끈다. 이 뒤로 이 프로세스의 기록은 없다");
      // 답이 나간 뒤에 끈다.
      setImmediate(() => app.quit());
      return null;
    },
  },
};
